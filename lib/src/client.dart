import 'dart:async';
import 'dart:convert';
import 'package:http/http.dart' as http;

import 'errors.dart';
import 'models.dart';

/// Official Dart and Flutter client for the K Khay Non-Custodial Crypto Payment Gateway.
///
/// Supports 190+ EVM, UTXO (Bitcoin, Dogecoin, Litecoin), Solana, TON, Tron, and XRPL networks
/// with 500+ cryptocurrencies and direct-to-wallet settlement.
class KkhayClient {
  final String apiKey;
  final String baseUrl;
  final Duration timeout;
  final http.Client _client;
  final bool _isCustomClient;

  KkhayClient({
    required String apiKey,
    String baseUrl = 'https://api.kkhay.com',
    Duration timeout = const Duration(seconds: 30),
    http.Client? httpClient,
  })  : apiKey = apiKey.trim(),
        baseUrl = baseUrl.replaceAll(RegExp(r'/+$'), ''),
        timeout = timeout,
        _client = httpClient ?? http.Client(),
        _isCustomClient = httpClient != null {
    if (this.apiKey.isEmpty) {
      throw ArgumentError('KkhayClient: apiKey is required and cannot be empty.');
    }
  }

  /// Resolves endpoint URLs across subdomains, main domains, and custom proxies.
  String _getUrl(String path) {
    final cleanPath = path.startsWith('/') ? path : '/$path';
    if (baseUrl.endsWith('/api') || baseUrl.contains('api.')) {
      return '$baseUrl$cleanPath';
    }
    return '$baseUrl/api$cleanPath';
  }

  /// Internal HTTP request dispatcher with error extraction.
  Future<Map<String, dynamic>> _request(
    String path, {
    String method = 'GET',
    Map<String, dynamic>? body,
  }) async {
    final uri = Uri.parse(_getUrl(path));
    final headers = {
      'Accept': 'application/json',
      'x-api-key': apiKey,
      'User-Agent': 'kkhay-dart/1.0.4',
    };

    final req = http.Request(method, uri);
    req.headers.addAll(headers);

    if (body != null) {
      req.headers['Content-Type'] = 'application/json';
      req.body = jsonEncode(body);
    }

    try {
      final streamedResponse = await _client.send(req).timeout(timeout);
      final response = await http.Response.fromStream(streamedResponse);
      final raw = response.body;

      Map<String, dynamic> decoded = {};
      try {
        if (raw.isNotEmpty) {
          decoded = jsonDecode(raw) as Map<String, dynamic>;
        }
      } catch (_) {}

      if (response.statusCode >= 400) {
        final message = decoded['message'] ?? decoded['error'] ?? 'HTTP ${response.statusCode} Error';
        throw KkhayApiException(
          response.statusCode,
          message.toString(),
          errorCode: decoded['code']?.toString(),
          details: decoded['details'],
        );
      }

      return decoded;
    } on TimeoutException {
      throw KkhayApiException(408, 'Request timed out after ${timeout.inSeconds}s');
    } on KkhayApiException {
      rethrow;
    } catch (e) {
      throw KkhayApiException(500, 'Network error: $e');
    }
  }

  /// Create a new non-custodial crypto payment invoice.
  Future<KkhayInvoice> createInvoice(CreateInvoiceRequest request) async {
    final res = await _request(
      '/v1/gateway/invoices',
      method: 'POST',
      body: request.toJson(),
    );

    return KkhayInvoice.fromJson(res['invoice'] as Map<String, dynamic>);
  }

  /// Retrieve the status, blockchain transactions, and details of a specific invoice.
  Future<GetInvoiceResponse> getInvoice(String invoiceId) async {
    if (invoiceId.trim().isEmpty) {
      throw ArgumentError('getInvoice: invoiceId is required');
    }

    final res = await _request('/v1/gateway/invoices/${Uri.encodeComponent(invoiceId.trim())}');
    return GetInvoiceResponse.fromJson(res);
  }

  /// List and filter invoices generated by your gateway account.
  Future<ListInvoicesResponse> listInvoices({
    int page = 1,
    int limit = 20,
    String? status,
    String? type,
    String? search,
  }) async {
    final params = <String, String>{
      'page': page.toString(),
      'limit': limit.toString(),
    };
    if (status != null && status.trim().isNotEmpty) {
      params['status'] = status.trim().toUpperCase();
    }
    if (type != null && type.trim().isNotEmpty) {
      params['type'] = type.trim().toUpperCase();
    }
    if (search != null && search.trim().isNotEmpty) {
      params['search'] = search.trim();
    }

    final query = Uri(queryParameters: params).query;
    final res = await _request('/v1/gateway/invoices?$query');
    return ListInvoicesResponse.fromJson(res);
  }

  /// Closes the underlying HTTP client.
  void close() {
    if (!_isCustomClient) {
      _client.close();
    }
  }
}
